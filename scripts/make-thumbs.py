"""Small card thumbnails (round 19, phone speed): assets/thumbs/<slug>.webp, 192x120 (2x the largest small slot, the
96x60 desk icons and "happening now" cards), made from each game's cover.png.

The home page used to load the full 640x400 cover PNG (up to 96 KB) for 48x30 chart rows and 96x60 desk icons. These
are 4-6 KB. Only covers of MIN_KB or more get one: most covers are tiny pixel-art PNGs (1-2 KB) that are already
smaller (and sharper) than any resized copy. The script also writes src/thumbs.js (the slugs that have a thumbnail);
src/pages.js uses the thumbnail for those and the cover for every other game.

  python scripts/make-thumbs.py            every game in games/games.json that has a cover.png
  python scripts/make-thumbs.py <slug> ... just those
Needs Pillow (pip install pillow). Run it after adding a game or changing a cover; commit the .webp files."""
import json, os, sys
from PIL import Image

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
OUT = os.path.join(ROOT, "assets", "thumbs")
W, H = 192, 120
MIN_KB = 8

games = json.load(open(os.path.join(ROOT, "games", "games.json"), encoding="utf-8"))["games"]
want = set(sys.argv[1:])
os.makedirs(OUT, exist_ok=True)
have = sorted(f[:-5] for f in os.listdir(OUT) if f.endswith(".webp"))
for g in games:
    slug = g.get("slug")
    if not slug or (want and slug not in want):
        continue
    src = os.path.join(ROOT, "games", slug, "cover.png")
    if not os.path.exists(src) or os.path.getsize(src) < MIN_KB * 1024:
        continue
    im = Image.open(src).convert("RGB")
    # fill the 16:10 slot like object-fit: cover does (covers are 640x400, so usually a plain resize)
    r = max(W / im.width, H / im.height)
    im = im.resize((max(W, round(im.width * r)), max(H, round(im.height * r))), Image.LANCZOS)
    x, y = (im.width - W) // 2, (im.height - H) // 2
    im = im.crop((x, y, x + W, y + H))
    dst = os.path.join(OUT, slug + ".webp")
    im.save(dst, "WEBP", quality=82, method=6)
    print(f"{slug:28} {os.path.getsize(src) // 1024:4d} KB png -> {os.path.getsize(dst) / 1024:5.1f} KB webp")
    if slug not in have:
        have.append(slug)

# the list the worker reads (only slugs whose .webp exists)
have = sorted(s for s in set(have) if os.path.exists(os.path.join(OUT, s + ".webp")))
with open(os.path.join(ROOT, "src", "thumbs.js"), "w", encoding="utf-8", newline="\n") as f:
    f.write("// Generated by scripts/make-thumbs.py: games with a small 192x120 card thumbnail (assets/thumbs/<slug>.webp).\n")
    f.write("export const THUMBS = new Set(" + json.dumps(have) + ");\n")
print("src/thumbs.js:", have)
